export function buildBusinessItemReport(
  topDim: string,
  scores: Record<string, number>,
  mbti: string,
  enn: string,
  badges: { label: string; value: string }[]
): FreeResult {
  const t = TYPES[topDim] ?? TYPES.strength;
  return {
    typeName: t.name,
    typeEmoji: t.emoji,
    tagline: t.tagline,
    badges,
    sections: t.sections(mbti, enn),
    summary: t.summary,
    scores,
  };
}
